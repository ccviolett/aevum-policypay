import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const SOURCES: Record<string, string> = {
  'contracts/AevumPolicyPayVault.sol': path.join(ROOT, 'contracts/AevumPolicyPayVault.sol'),
  'contracts/test/MockTUSD8.sol': path.join(ROOT, 'contracts/test/MockTUSD8.sol'),
};

interface SolcMessage {
  severity: 'error' | 'warning' | 'info';
  formattedMessage: string;
}

interface SolcContractOutput {
  abi: unknown[];
  evm: {
    bytecode: { object: string };
    deployedBytecode: { object: string };
  };
}

interface SolcOutput {
  errors?: SolcMessage[];
  contracts?: Record<string, Record<string, SolcContractOutput>>;
}

function main() {
  const inputSources: Record<string, { content: string }> = {};
  for (const [key, fullPath] of Object.entries(SOURCES)) {
    inputSources[key] = { content: fs.readFileSync(fullPath, 'utf8') };
  }

  const input = {
    language: 'Solidity',
    sources: inputSources,
    settings: {
      evmVersion: 'shanghai',
      optimizer: {
        enabled: true,
        runs: 200,
      },
      outputSelection: {
        '*': {
          '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'],
        },
      },
    },
  };

  const rawOutput = solc.compile(JSON.stringify(input));
  const output: SolcOutput = JSON.parse(rawOutput);

  const errors = (output.errors ?? []).filter((m) => m.severity === 'error');
  const warnings = (output.errors ?? []).filter((m) => m.severity === 'warning');

  if (errors.length > 0 || warnings.length > 0) {
    for (const msg of [...errors, ...warnings]) {
      console.error(msg.formattedMessage);
    }
    throw new Error(
      `Solidity compilation failed strict zero-warning check (${errors.length} errors, ${warnings.length} warnings)`
    );
  }

  const artifactsDir = path.join(ROOT, 'artifacts');
  const generatedDir = path.join(ROOT, 'shared/generated');
  fs.mkdirSync(artifactsDir, { recursive: true });
  fs.mkdirSync(generatedDir, { recursive: true });

  const targets: Array<{ source: string; name: string }> = [
    { source: 'contracts/AevumPolicyPayVault.sol', name: 'AevumPolicyPayVault' },
    { source: 'contracts/test/MockTUSD8.sol', name: 'MockTUSD8' },
  ];

  for (const target of targets) {
    const compiled = output.contracts?.[target.source]?.[target.name];
    if (!compiled || !compiled.evm.bytecode.object) {
      throw new Error(`Missing compiled bytecode for ${target.name}`);
    }

    const artifact = {
      contractName: target.name,
      sourceName: target.source,
      compiler: {
        version: solc.version(),
        evmVersion: 'shanghai',
        optimizer: { enabled: true, runs: 200 },
      },
      abi: compiled.abi,
      bytecode: `0x${compiled.evm.bytecode.object}` as const,
      deployedBytecode: `0x${compiled.evm.deployedBytecode.object}` as const,
      bytecodeSizeBytes: compiled.evm.bytecode.object.length / 2,
      deployedBytecodeSizeBytes: compiled.evm.deployedBytecode.object.length / 2,
    };

    fs.writeFileSync(
      path.join(artifactsDir, `${target.name}.json`),
      JSON.stringify(artifact, null, 2) + '\n'
    );

    if (target.name === 'AevumPolicyPayVault') {
      const tsOut = [
        '// Auto-generated by scripts/compile.ts — DO NOT EDIT MANUALLY',
        `export const AEVUM_POLICY_PAY_VAULT_ABI = ${JSON.stringify(compiled.abi, null, 2)} as const;`,
        `export const AEVUM_POLICY_PAY_VAULT_BYTECODE = ${JSON.stringify(artifact.bytecode)} as const;`,
        '',
      ].join('\n');
      fs.writeFileSync(path.join(generatedDir, 'AevumPolicyPayVaultAbi.ts'), tsOut);
    }

    console.log(
      `Compiled ${target.name} (${solc.version()}, shanghai): runtime ${artifact.deployedBytecodeSizeBytes} bytes (0 warnings)`
    );
  }
}

main();
